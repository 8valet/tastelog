// Compile the canonical scoped sources. The design preview is a reference,
// not the source of truth for subsequent production UI refinements.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import postcss from 'postcss';
const sources = ['library-base.css', 'library-additions.css'].map(name => readFileSync(`app/(en)/library/${name}`, 'utf8'));
for (const source of sources) postcss.parse(source);
const target = 'app/(en)/library/library.css';
const output = `/* Generated by scripts/build-library-css.mjs; edit the canonical base/additions files. */\n${sources.join('\n')}`;
if (!existsSync(target) || readFileSync(target, 'utf8') !== output) writeFileSync(target, output);
